//! Pure policy classifier; not an authorization boundary.

pub mod wifi;
#[derive(Debug, PartialEq, Eq, Clone, Copy)]
pub enum Action { Read, Write, Export, Execute, ChangePolicy, Unknown }
#[derive(Debug, PartialEq, Eq)]
pub enum Decision { Deny, RequireApproval, Allow }
pub fn classify(action: Action, integrated: bool, scoped: bool) -> Decision {
    if !integrated || !scoped { return Decision::Deny; }
    match action {
        Action::Read => Decision::Allow,
        Action::Write | Action::Export => Decision::RequireApproval,
        Action::Execute | Action::ChangePolicy | Action::Unknown => Decision::Deny,
    }
}
#[cfg(test)]
mod tests {
    use super::*;
    const ACTIONS: [Action;6] = [Action::Read, Action::Write, Action::Export, Action::Execute, Action::ChangePolicy, Action::Unknown];
    #[test] fn fail_closed() {
        for action in ACTIONS {
            for (integrated, scoped) in [(false,true),(true,false),(false,false)] {
                assert_eq!(classify(action, integrated, scoped), Decision::Deny);
            }
        }
    }
    #[test] fn sensitive_requires_approval() {
        for action in [Action::Write, Action::Export] {
            assert_eq!(classify(action, true, true), Decision::RequireApproval);
        }
    }
    #[test] fn read_only() { assert_eq!(classify(Action::Read,true,true), Decision::Allow); }
    #[test] fn privileged_and_unknown_denied() {
        for action in [Action::Execute,Action::ChangePolicy,Action::Unknown] {
            assert_eq!(classify(action,true,true),Decision::Deny);
        }
    }
}


/// ALIS offline synthetic admission rehearsal. Not a production trust boundary.
/// No network, persistence, raw payloads, learning or cryptographic verification.
pub mod alis {
    use std::collections::{BTreeMap, BTreeSet};

    pub const MAX_BATCH: usize = 256;

    #[derive(Clone, Copy, Debug, PartialEq, Eq)]
    pub enum Verdict {
        CandidateOnly, UnverifiedSource, WrongSchema, InvalidDigest,
        Duplicate, SourceQuota, GroupQuota,
    }

    #[derive(Clone, Copy, Debug, PartialEq, Eq)]
    pub enum BatchError { InvalidConfiguration, BatchTooLarge }

    /// Metadata generated by the synthetic harness; not a trusted identity assertion.
    #[derive(Clone, Copy)]
    pub struct Fixture {
        pub source: u16,
        pub schema: u16,
        pub digest: [u8; 32],
        pub verified_by_mock: bool,
    }

    /// Source-to-group assignment is supplied separately from observations.
    pub struct Config {
        pub schema: u16,
        pub sources: Vec<(u16, u16)>,
        pub source_cap: usize,
        pub group_cap: usize,
    }

    /// Pure bounded batch classifier. All rejected records remain outside the
    /// candidate set. Caller owns quarantine evidence and retention; this function
    /// neither deletes nor retains payloads. Input order is explicit, first eligible
    /// occurrence wins. Quotas reset per batch: never use as a production quota.
    pub fn rehearse(config: &Config, batch: &[Fixture]) -> Result<Vec<Verdict>, BatchError> {
        if config.schema == 0 || config.sources.is_empty() ||
            config.sources.len() > MAX_BATCH || config.source_cap == 0 ||
            config.group_cap == 0 || config.source_cap > config.group_cap ||
            config.group_cap > MAX_BATCH {
            return Err(BatchError::InvalidConfiguration);
        }
        let mut registry = BTreeMap::new();
        for &(source, group) in &config.sources {
            if source == 0 || group == 0 || registry.insert(source, group).is_some() {
                return Err(BatchError::InvalidConfiguration);
            }
        }
        if batch.len() > MAX_BATCH { return Err(BatchError::BatchTooLarge); }
        let mut seen = BTreeSet::new();
        let mut source_counts = BTreeMap::<u16, usize>::new();
        let mut group_counts = BTreeMap::<u16, usize>::new();
        let mut results = Vec::with_capacity(batch.len());
        for item in batch {
            let verdict = match registry.get(&item.source).copied() {
                Some(group) if item.verified_by_mock => {
                    if item.schema != config.schema { Verdict::WrongSchema }
                    else if item.digest == [0; 32] { Verdict::InvalidDigest }
                    else if seen.contains(&item.digest) { Verdict::Duplicate }
                    else if source_counts.get(&item.source).copied().unwrap_or(0) >= config.source_cap {
                        Verdict::SourceQuota
                    } else if group_counts.get(&group).copied().unwrap_or(0) >= config.group_cap {
                        Verdict::GroupQuota
                    } else {
                        seen.insert(item.digest);
                        *source_counts.entry(item.source).or_default() += 1;
                        *group_counts.entry(group).or_default() += 1;
                        Verdict::CandidateOnly
                    }
                }
                _ => Verdict::UnverifiedSource,
            };
            results.push(verdict);
        }
        Ok(results)
    }

    #[cfg(test)]
    mod tests {
        use super::*;
        fn config() -> Config {
            Config { schema: 1, sources: vec![(1, 10), (2, 10), (3, 20)],
                source_cap: 2, group_cap: 3 }
        }
        fn sample(source: u16, marker: u8) -> Fixture {
            Fixture { source, schema: 1, digest: [marker; 32], verified_by_mock: true }
        }
        #[test]
        fn eligible_is_only_candidate() {
            assert_eq!(rehearse(&config(), &[sample(1, 1)]), Ok(vec![Verdict::CandidateOnly]));
        }
        #[test]
        fn rejects_unverified_and_unknown_sources_without_consuming_quota() {
            let mut unverified = sample(1, 1);
            unverified.verified_by_mock = false;
            assert_eq!(rehearse(&config(), &[unverified, sample(99, 1), sample(1, 1)]),
                Ok(vec![Verdict::UnverifiedSource, Verdict::UnverifiedSource, Verdict::CandidateOnly]));
        }
        #[test]
        fn rejects_wrong_schema_and_empty_digest() {
            let mut wrong = sample(1, 1);
            wrong.schema = 2;
            assert_eq!(rehearse(&config(), &[wrong, sample(1, 0), sample(1, 1)]),
                Ok(vec![Verdict::WrongSchema, Verdict::InvalidDigest, Verdict::CandidateOnly]));
        }
        #[test]
        fn duplicate_is_global_and_does_not_consume_quota() {
            assert_eq!(rehearse(&config(), &[sample(1, 1), sample(2, 1), sample(2, 2), sample(2, 3)]),
                Ok(vec![Verdict::CandidateOnly, Verdict::Duplicate, Verdict::CandidateOnly, Verdict::CandidateOnly]));
        }
        #[test]
        fn source_and_group_caps_and_independent_group() {
            assert_eq!(rehearse(&config(), &[sample(1, 1), sample(1, 2), sample(1, 3),
                sample(2, 3), sample(2, 4), sample(3, 4)]),
                Ok(vec![Verdict::CandidateOnly, Verdict::CandidateOnly, Verdict::SourceQuota,
                    Verdict::CandidateOnly, Verdict::GroupQuota, Verdict::CandidateOnly]));
        }
        #[test]
        fn invalid_config_fails_whole_batch() {
            let mut c = config();
            c.sources.push((1, 20));
            assert_eq!(rehearse(&c, &[]), Err(BatchError::InvalidConfiguration));
            let mut c = config();
            c.source_cap = 0;
            assert_eq!(rehearse(&c, &[]), Err(BatchError::InvalidConfiguration));
            let mut c = config();
            c.group_cap = MAX_BATCH + 1;
            assert_eq!(rehearse(&c, &[]), Err(BatchError::InvalidConfiguration));
        }
        #[test]
        fn batch_limit_and_empty_batch() {
            assert_eq!(rehearse(&config(), &vec![sample(1, 1); MAX_BATCH + 1]),
                Err(BatchError::BatchTooLarge));
            assert_eq!(rehearse(&config(), &[]), Ok(vec![]));
            let r = rehearse(&config(), &vec![sample(1, 1); MAX_BATCH]).unwrap();
            assert_eq!(r.len(), MAX_BATCH);
            assert_eq!(r.iter().filter(|v| **v == Verdict::CandidateOnly).count(), 1);
        }
        #[test]
        fn deterministic_rehearsal_not_persistent_learning() {
            let batch = [sample(1, 1), sample(2, 1), sample(3, 2)];
            assert_eq!(rehearse(&config(), &batch), rehearse(&config(), &batch));
        }
    }
}


/// ALIS-02: bounded, deterministic comparison of synthetic aggregate windows.
/// Advisory only: no authenticated baseline, statistical calibration, learning,
/// persistence, system action, or production authorization.
pub mod alis_drift {
    pub const MAX_SAMPLES: u32 = 1_000_000;
    pub const SCALE: u64 = 1_000_000;

    #[derive(Clone, Copy, Debug, PartialEq, Eq)]
    pub struct Window {
        pub observed: u32,
        pub flagged: u32,
    }

    #[derive(Clone, Copy, Debug, PartialEq, Eq)]
    pub struct Config {
        pub min_samples: u32,
        pub tolerance_ppm: u32,
        pub reference_version: u64,
    }

    #[derive(Clone, Copy, Debug, PartialEq, Eq)]
    pub enum Verdict {
        InvalidConfiguration,
        InvalidWindow,
        InsufficientEvidence,
        WithinTolerance,
        ReviewRequired,
    }

    /// Compare absolute differences between observed proportions, exactly as
    /// rational numbers. Equality at the threshold is within tolerance.
    /// Config and frozen reference must come from a separate trusted authority
    /// in a real integration; a version number alone proves no authenticity.
    /// No observation can modify the reference or authorize training.
    pub fn compare(config: Config, reference: Window, current: Window) -> Verdict {
        if config.reference_version == 0 || config.min_samples == 0 ||
            config.min_samples > MAX_SAMPLES || u64::from(config.tolerance_ppm) > SCALE {
            return Verdict::InvalidConfiguration;
        }
        for w in [reference, current] {
            if w.observed > MAX_SAMPLES || w.flagged > w.observed {
                return Verdict::InvalidWindow;
            }
        }
        if reference.observed < config.min_samples || current.observed < config.min_samples {
            return Verdict::InsufficientEvidence;
        }
        // Products <= 10^12, scaled products <= 10^18: fit in u64.
        let a = u64::from(reference.flagged) * u64::from(current.observed);
        let b = u64::from(current.flagged) * u64::from(reference.observed);
        let denominator = u64::from(reference.observed) * u64::from(current.observed);
        if a.abs_diff(b) * SCALE > denominator * u64::from(config.tolerance_ppm) {
            Verdict::ReviewRequired
        } else {
            Verdict::WithinTolerance
        }
    }

    #[cfg(test)]
    mod tests {
        use super::*;
        fn config() -> Config {
            Config { min_samples: 100, tolerance_ppm: 20_000, reference_version: 1 }
        }
        fn w(observed: u32, flagged: u32) -> Window { Window { observed, flagged } }
        #[test]
        fn same_proportion_different_window_sizes() {
            assert_eq!(compare(config(), w(100, 10), w(1000, 100)), Verdict::WithinTolerance);
        }
        #[test]
        fn threshold_inclusive_and_both_directions() {
            assert_eq!(compare(config(), w(100, 10), w(100, 12)), Verdict::WithinTolerance);
            assert_eq!(compare(config(), w(100, 10), w(100, 8)), Verdict::WithinTolerance);
            assert_eq!(compare(config(), w(100, 10), w(100, 13)), Verdict::ReviewRequired);
            assert_eq!(compare(config(), w(100, 10), w(100, 7)), Verdict::ReviewRequired);
        }
        #[test]
        fn zero_reference_and_small_fraction() {
            assert_eq!(compare(config(), w(100, 0), w(100, 3)), Verdict::ReviewRequired);
            assert_eq!(compare(config(), w(100, 0), w(101, 2)), Verdict::WithinTolerance);
            let mut c = config();
            c.tolerance_ppm = 0;
            assert_eq!(compare(c, w(MAX_SAMPLES, 0), w(MAX_SAMPLES, 1)), Verdict::ReviewRequired);
        }
        #[test]
        fn missing_and_small_windows_are_not_stable() {
            assert_eq!(compare(config(), w(0, 0), w(100, 0)), Verdict::InsufficientEvidence);
            assert_eq!(compare(config(), w(100, 0), w(99, 0)), Verdict::InsufficientEvidence);
        }
        #[test]
        fn invalid_windows_fail_closed() {
            assert_eq!(compare(config(), w(100, 101), w(100, 0)), Verdict::InvalidWindow);
            assert_eq!(compare(config(), w(100, 0), w(MAX_SAMPLES + 1, 0)), Verdict::InvalidWindow);
            assert_eq!(compare(config(), w(0, 1), w(0, 0)), Verdict::InvalidWindow);
        }
        #[test]
        fn invalid_configuration() {
            for c in [
                Config { reference_version: 0, ..config() },
                Config { min_samples: 0, ..config() },
                Config { min_samples: MAX_SAMPLES + 1, ..config() },
                Config { tolerance_ppm: 1_000_001, ..config() },
            ] {
                assert_eq!(compare(c, w(100, 0), w(100, 0)), Verdict::InvalidConfiguration);
            }
        }
        #[test]
        fn maximum_bounds_do_not_overflow() {
            assert_eq!(compare(config(), w(MAX_SAMPLES, 0), w(MAX_SAMPLES, MAX_SAMPLES)),
                Verdict::ReviewRequired);
            let c = Config { tolerance_ppm: 1_000_000, ..config() };
            assert_eq!(compare(c, w(MAX_SAMPLES, 0), w(MAX_SAMPLES, MAX_SAMPLES)),
                Verdict::WithinTolerance);
        }
        #[test]
        fn successive_small_changes_use_same_frozen_reference() {
            let reference = w(1000, 100);
            for (flagged, expected) in [(110, Verdict::WithinTolerance),
                (120, Verdict::WithinTolerance), (130, Verdict::ReviewRequired)] {
                assert_eq!(compare(config(), reference, w(1000, flagged)), expected);
            }
            assert_eq!(reference, w(1000, 100));
        }
    }
}


/// ALIS-03: deterministic offline fixture precheck. This is NOT a deployment
/// authority, signature verifier, or evidence of actual independent evaluation.
pub mod alis_promotion {
    pub type Digest = [u8; 32];

    #[derive(Clone, Copy, Debug, PartialEq, Eq)]
    pub struct Binding {
        pub model: Digest,
        pub training_manifest: Digest,
        pub holdout_manifest: Digest,
        pub reference: Digest,
        pub policy_version: u64,
    }

    #[derive(Clone, Copy, Debug, PartialEq, Eq)]
    pub struct MockEvidence {
        pub evaluated: Binding,
        pub reviewed: Binding,
        pub expected_policy_version: u64,
        pub lineage_verified_in_fixture: bool,
        pub quarantine_clear_in_fixture: bool,
        pub split_disjoint_in_fixture: bool,
        pub invariant_failures: u32,
        pub evaluated_cases: u32,
        pub statistical_gate_passed_in_fixture: bool,
        pub independent_review_in_fixture: bool,
        pub rollback_verified_in_fixture: bool,
    }

    #[derive(Clone, Copy, Debug, PartialEq, Eq)]
    pub enum Verdict {
        InvalidBinding,
        PolicyMismatch,
        EvidenceMismatch,
        LineageOrQuarantine,
        HoldoutNotDisjoint,
        InvariantFailureOrEmptyEvaluation,
        StatisticalGateMissing,
        ReviewMissing,
        RollbackMissing,
        EligibleForExternalReviewOnly,
    }

    /// Caller-supplied fixture flags prove nothing about real evidence.
    /// Manifest inequality does not establish record-level disjointness.
    /// This precheck never grants deployment, training or privilege changes.
    pub fn precheck(candidate: Binding, evidence: MockEvidence) -> Verdict {
        if candidate.policy_version == 0 ||
            [candidate.model, candidate.training_manifest, candidate.holdout_manifest,
             candidate.reference].contains(&[0; 32]) {
            return Verdict::InvalidBinding;
        }
        if candidate.policy_version != evidence.expected_policy_version {
            return Verdict::PolicyMismatch;
        }
        if evidence.evaluated != candidate || evidence.reviewed != candidate {
            return Verdict::EvidenceMismatch;
        }
        if !evidence.lineage_verified_in_fixture || !evidence.quarantine_clear_in_fixture {
            return Verdict::LineageOrQuarantine;
        }
        if candidate.training_manifest == candidate.holdout_manifest ||
            !evidence.split_disjoint_in_fixture {
            return Verdict::HoldoutNotDisjoint;
        }
        if evidence.evaluated_cases == 0 || evidence.invariant_failures != 0 {
            return Verdict::InvariantFailureOrEmptyEvaluation;
        }
        if !evidence.statistical_gate_passed_in_fixture {
            return Verdict::StatisticalGateMissing;
        }
        if !evidence.independent_review_in_fixture {
            return Verdict::ReviewMissing;
        }
        if !evidence.rollback_verified_in_fixture {
            return Verdict::RollbackMissing;
        }
        Verdict::EligibleForExternalReviewOnly
    }

    #[cfg(test)]
    mod tests {
        use super::*;
        fn binding() -> Binding {
            Binding { model: [1; 32], training_manifest: [2; 32],
                holdout_manifest: [3; 32], reference: [4; 32], policy_version: 1 }
        }
        fn evidence(b: Binding) -> MockEvidence {
            MockEvidence { evaluated: b, reviewed: b, expected_policy_version: 1,
                lineage_verified_in_fixture: true, quarantine_clear_in_fixture: true,
                split_disjoint_in_fixture: true, invariant_failures: 0,
                evaluated_cases: 100, statistical_gate_passed_in_fixture: true,
                independent_review_in_fixture: true, rollback_verified_in_fixture: true }
        }
        #[test]
        fn all_fixture_gates_only_enable_external_review() {
            let b = binding();
            assert_eq!(precheck(b, evidence(b)), Verdict::EligibleForExternalReviewOnly);
        }
        #[test]
        fn zero_identifiers_and_version_rejected() {
            let b = binding();
            for invalid in [Binding { model: [0; 32], ..b },
                Binding { training_manifest: [0; 32], ..b },
                Binding { holdout_manifest: [0; 32], ..b },
                Binding { reference: [0; 32], ..b },
                Binding { policy_version: 0, ..b }] {
                assert_eq!(precheck(invalid, evidence(invalid)), Verdict::InvalidBinding);
            }
        }
        #[test]
        fn stale_policy_rejected_even_if_evidence_agrees() {
            let b = binding();
            assert_eq!(precheck(b, MockEvidence { expected_policy_version: 2, ..evidence(b) }),
                Verdict::PolicyMismatch);
        }
        #[test]
        fn evidence_and_review_bound_to_every_field() {
            let b = binding();
            for changed in [Binding { model: [9; 32], ..b },
                Binding { training_manifest: [9; 32], ..b },
                Binding { holdout_manifest: [9; 32], ..b },
                Binding { reference: [9; 32], ..b },
                Binding { policy_version: 2, ..b }] {
                assert_eq!(precheck(b, MockEvidence { evaluated: changed, ..evidence(b) }),
                    Verdict::EvidenceMismatch);
                assert_eq!(precheck(b, MockEvidence { reviewed: changed, ..evidence(b) }),
                    Verdict::EvidenceMismatch);
            }
        }
        #[test]
        fn quarantine_and_lineage_are_required() {
            let b = binding();
            for e in [MockEvidence { lineage_verified_in_fixture: false, ..evidence(b) },
                MockEvidence { quarantine_clear_in_fixture: false, ..evidence(b) }] {
                assert_eq!(precheck(b, e), Verdict::LineageOrQuarantine);
            }
        }
        #[test]
        fn equal_manifests_or_missing_split_evidence_rejected() {
            let b = binding();
            let same = Binding { holdout_manifest: b.training_manifest, ..b };
            assert_eq!(precheck(same, evidence(same)), Verdict::HoldoutNotDisjoint);
            assert_eq!(precheck(b, MockEvidence { split_disjoint_in_fixture: false, ..evidence(b) }),
                Verdict::HoldoutNotDisjoint);
        }
        #[test]
        fn empty_evaluation_or_single_invariant_failure_rejected() {
            let b = binding();
            for e in [MockEvidence { evaluated_cases: 0, ..evidence(b) },
                MockEvidence { invariant_failures: 1, ..evidence(b) }] {
                assert_eq!(precheck(b, e), Verdict::InvariantFailureOrEmptyEvaluation);
            }
        }
        #[test]
        fn statistical_review_and_rollback_gates_are_individually_required() {
            let b = binding();
            assert_eq!(precheck(b, MockEvidence { statistical_gate_passed_in_fixture: false, ..evidence(b) }),
                Verdict::StatisticalGateMissing);
            assert_eq!(precheck(b, MockEvidence { independent_review_in_fixture: false, ..evidence(b) }),
                Verdict::ReviewMissing);
            assert_eq!(precheck(b, MockEvidence { rollback_verified_in_fixture: false, ..evidence(b) }),
                Verdict::RollbackMissing);
        }
    }
}
